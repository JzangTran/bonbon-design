// Generates the platform files from tokens/: dist/tokens.css (web), dist/tokens.ts (React Native), dist/tokens.json.
// `--sync` also copies them into the sibling web/ and mobile/ checkouts of the bonbon umbrella repo.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { descriptions, foundation, palette, roles, themes } from './tokens.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dist = join(root, 'dist')
mkdirSync(dist, { recursive: true })

const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const header = (comment) =>
  `${comment} Generated by bonbon-design v${version} from tokens/*.json. Do not edit: change the source tokens and run \`npm run build\`.\n`

const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase()).replace(/(\D)(\d)/g, '$1-$2')
const { font, type, space, radius, elevation, motion, layout, icon } = foundation
const clean = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('$')))

// ---------- web: CSS custom properties, --bb-* ----------
const css = []
css.push(header('/*').replace(/\n$/, ' */\n'))
css.push(':root {')
for (const [name, steps] of Object.entries(palette)) for (const [step, hex] of Object.entries(steps)) css.push(`  --bb-${name}-${step}: ${hex};`)
for (const r of roles) css.push(`  --bb-${kebab(r)}: ${themes.light[r]};${descriptions[r] ? ` /* ${descriptions[r]} */` : ''}`)
css.push(`  --bb-font-sans: '${font.family}', ${font.fallback};`)
css.push(`  --bb-font-mono: ${font.mono};`)
for (const [k, v] of Object.entries(clean(font.weights))) css.push(`  --bb-weight-${k}: ${v};`)
for (const [k, t] of Object.entries(clean(type))) {
  css.push(`  --bb-text-${kebab(k)}: ${t.size / 16}rem;`)
  css.push(`  --bb-text-${kebab(k)}-line: ${t.lineHeight / 16}rem;`)
  css.push(`  --bb-text-${kebab(k)}-weight: ${font.weights[t.weight]};`)
  css.push(`  --bb-text-${kebab(k)}-tracking: ${t.tracking}em;`)
}
for (const [k, v] of Object.entries(clean(space))) css.push(`  --bb-space-${k}: ${v / 16}rem;`)
for (const [k, v] of Object.entries(clean(radius))) css.push(`  --bb-radius-${k}: ${v}px;`)
for (const [k, v] of Object.entries(clean(elevation))) css.push(`  --bb-elevation-${k}: ${v};`)
for (const [k, v] of Object.entries(clean(motion))) css.push(`  --bb-motion-${kebab(k)}: ${typeof v === 'number' ? v + 'ms' : v};`)
css.push(`  --bb-content-max: ${layout.contentMax}px;`)
css.push(`  --bb-reading-max: ${layout.readingMax}px;`)
css.push('}')
css.push('')
css.push('.dark {')
for (const r of roles) css.push(`  --bb-${kebab(r)}: ${themes.dark[r]};`)
css.push('  color-scheme: dark;')
css.push('}')
css.push('')
css.push('@media (prefers-reduced-motion: reduce) {')
css.push('  :root { --bb-motion-fast: 0ms; --bb-motion-base: 0ms; --bb-motion-slow: 0ms; }')
css.push('}')
writeFileSync(join(dist, 'tokens.css'), css.join('\n') + '\n')

// ---------- mobile: TypeScript module ----------
const fileByWeight = { 400: '400Regular', 500: '500Medium', 600: '600SemiBold', 700: '700Bold', 800: '800ExtraBold' }
// the file follows the weight a name resolves to, so bold and extrabold load the semibold file (never bold, owner 2026-11-19)
const fontKey = Object.fromEntries(Object.entries(font.weights).filter(([k]) => !k.startsWith('$')).map(([k, w]) => [k, fileByWeight[w]]))
const familyId = font.family.replace(/\s+/g, '')
const ts = []
ts.push(header('//'))
ts.push(`export const palette = ${JSON.stringify(palette, null, 2)} as const\n`)
ts.push(`const light = ${JSON.stringify(themes.light, null, 2)} as const\n`)
ts.push('export type ColorScheme = { [K in keyof typeof light]: string }\n')
ts.push(`const dark: ColorScheme = ${JSON.stringify(themes.dark, null, 2)}\n`)
ts.push('export const colors = { light: light as ColorScheme, dark }\n')
ts.push(`/** ${font.family}: load these with @expo-google-fonts/be-vietnam-pro; every weight name resolves to at most semibold. */`)
ts.push(`export const fonts = ${JSON.stringify(Object.fromEntries(Object.keys(clean(font.weights)).map((k) => [k, `${familyId}_${fontKey[k]}`])), null, 2)} as const\n`)
const typeTs = Object.fromEntries(
  Object.entries(clean(type)).map(([k, t]) => [k, { fontSize: t.size, lineHeight: t.lineHeight, fontFamily: `${familyId}_${fontKey[t.weight]}`, letterSpacing: +(t.tracking * t.size).toFixed(2) }]),
)
ts.push('/** The eight named text styles. Screens use these through <Text variant>, never a raw size. */')
ts.push(`export const type = ${JSON.stringify(typeTs, null, 2)} as const\n`)
ts.push('export type TypeStyle = keyof typeof type\n')
ts.push(`export const space = ${JSON.stringify(clean(space), null, 2)} as const\n`)
ts.push(`export const radius = ${JSON.stringify(clean(radius), null, 2)} as const\n`)
ts.push(`export const motion = ${JSON.stringify(Object.fromEntries(Object.entries(clean(motion)).filter(([, v]) => typeof v === 'number')), null, 2)} as const\n`)
ts.push(`export const layout = ${JSON.stringify(layout, null, 2)} as const\n`)
ts.push(`export const icon = ${JSON.stringify(icon, null, 2)} as const\n`)
ts.push('/** Fluent shadows on React Native (iOS shadow + Android elevation), for layers above the page only: raised = shadow8, overlay = shadow16 for menus, sheets and snackbars. Cards never cast a shadow. */')
ts.push('export const shadows = {')
ts.push('  raised: { shadowColor: "#000000", shadowOpacity: 0.14, shadowRadius: 8, shadowOffset: { width: 0, height: 4 }, elevation: 4 },')
ts.push('  overlay: { shadowColor: "#000000", shadowOpacity: 0.14, shadowRadius: 16, shadowOffset: { width: 0, height: 8 }, elevation: 8 },')
ts.push('} as const')
ts.push('export const overlayShadow = shadows.overlay')
writeFileSync(join(dist, 'tokens.ts'), ts.join('\n') + '\n')

writeFileSync(join(dist, 'tokens.json'), JSON.stringify({ version, palette, themes, foundation }, null, 2) + '\n')
console.log(`built dist/tokens.css, dist/tokens.ts, dist/tokens.json (${roles.length} roles, ${version})`)

if (process.argv.includes('--sync')) {
  const umbrella = join(root, '..')
  const targets = [
    [join(dist, 'tokens.css'), join(umbrella, 'web', 'src', 'shared', 'ui', 'generated', 'tokens.css')],
    [join(dist, 'tokens.ts'), join(umbrella, 'mobile', 'src', 'shared', 'ui', 'generated', 'tokens.ts')],
  ]
  for (const [from, to] of targets) {
    if (!existsSync(join(to, '..', '..'))) {
      console.warn(`skip ${to}: no checkout there`)
      continue
    }
    mkdirSync(dirname(to), { recursive: true })
    copyFileSync(from, to)
    console.log(`synced ${to}`)
  }
}
